/** The alias the key of an inserted or updated row is returned under. */
internal const val KEY_ALIAS: String = "stx_key"

/** The alias another returned column of a written row is returned under. */
internal fun returnedAlias(column: TableField<*, *>): String = "stx_${column.name}"

/** The values of one row to write, by column. */
internal typealias RowValues = Map<Field<*>, Any?>

/**
 * Postgres accepts at most 65535 bind values per statement; multi-row statements are split into
 * chunks that stay well below that.
 */
private const val MAX_BIND_VALUES_PER_STATEMENT = 30_000

/** The number of rows of [columns] columns one statement may hold. */
internal fun rowsPerStatement(columns: Int): Int =
    maxOf(
        1,
        MAX_BIND_VALUES_PER_STATEMENT / maxOf(1, columns),
    )

/** Writes rows through [executor], building the statements with [dsl]. */
internal class RowWriter(
    val dsl: DSLContext,
    val executor: QueryExecutor,
)

/**
 * [maps] merged into one, failing when two of them hold the same column: a column written from two
 * places is a configuration error, never something to resolve silently.
 */
internal fun mergeDisjoint(vararg maps: RowValues): RowValues {
    val merged = LinkedHashMap<Field<*>, Any?>()
    maps.forEach { map ->
        map.forEach { (column, value) ->
            require(column !in merged) { "Column '${column.name}' is written more than once" }

            merged[column] = value
        }
    }

    return merged
}

/** The columns every one of [rows] writes; they must all write the same columns. */
internal fun columnsOf(rows: List<RowValues>): List<Field<*>> {
    val columns = rows.first().keys.toList()
    rows.forEach { row ->
        require(row.keys == columns.toSet()) {
            "Rows of one statement must write the same columns: ${columns.map {
                it.name
            }} vs ${row.keys.map { it.name }}"
        }
    }

    return columns
}

/** Inserts [rows] into [table] with as few multi-row `INSERT`s as possible. */
internal suspend fun RowWriter.insertRows(
    table: Table<*>,
    rows: List<RowValues>,
) {
    if (rows.isEmpty()) return
    val columns = columnsOf(rows)
    rows.chunked(rowsPerStatement(columns.size)).forEach { chunk ->
        val affected = executor.executeUpdate(insertQuery(table, columns, chunk))
        check(affected == chunk.size) {
            "INSERT into '${table.name}' affected $affected rows, expected ${chunk.size}"
        }
    }
}

/**
 * Inserts [rows] into [table] and returns, per row and in input order, its [key] (as [KEY_ALIAS])
 * and the [returned] columns (as [returnedAlias]).
 *
 * Rows are matched back to the input by [key] when the input supplies it (an id generated by the
 * application), and otherwise by position - Postgres returns the rows of a plain multi-row
 * `INSERT ... VALUES` in input order.
 */
internal suspend fun RowWriter.insertReturning(
    table: Table<*>,
    key: TableField<*, *>,
    rows: List<RowValues>,
    returned: List<TableField<*, *>> = emptyList(),
): List<RowContext> {
    if (rows.isEmpty()) return emptyList()
    val columns = columnsOf(rows)
    val returning =
        listOf(key.`as`(KEY_ALIAS)) + returned.distinct().map { it.`as`(returnedAlias(it)) }

    return rows.chunked(rowsPerStatement(columns.size)).flatMap { chunk ->
        val inserted =
            executor.executeAndGetAll(
                insertQuery(table, columns, chunk).returning(returning),
            )
        check(inserted.size == chunk.size) {
            "INSERT into '${table.name}' returned ${inserted.size} rows, expected ${chunk.size}"
        }

        if (key in columns) {
            val byKey = inserted.associateBy { it.rawOrNull(KEY_ALIAS) }

            chunk.map { row ->
                byKey[row[key]]
                    ?: throw IllegalStateException(
                        "INSERT into '${table.name}' did not return key '${row[key]}'",
                    )
            }
        } else {
            inserted
        }
    }
}

private fun RowWriter.insertQuery(
    table: Table<*>,
    columns: List<Field<*>>,
    rows: List<RowValues>,
) = rows.fold(dsl.insertInto(table, columns)) { step, row -> step.values(columns.map { row[it] }) }

/**
 * The foreign-key values [resolves] write for each of [elements], in order: per element a map from
 * [GroupFkResolve.fkColumn] to the referenced row's [GroupFkResolve.targetColumn] value, `null` when
 * the element references nothing, and no entry when [GroupFkResolve.skip] leaves the column alone.
 * Every resolve is looked up with one query for all elements.
 *
 * @throws ReferencedEntityNotFoundException for the first referenced row that does not exist.
 */
internal suspend fun <E> RowWriter.resolveForeignKeys(
    resolves: List<GroupFkResolve<E>>,
    elements: List<E>,
): List<RowValues> {
    if (resolves.isEmpty()) return elements.map { emptyMap() }

    val lookups =
        resolves.map { resolve ->
            val lookupValues =
                elements
                    .filterNot(
                        resolve.skip,
                    ).mapNotNull(resolve.valueSupplier)
                    .toSet()
            lookup(resolve.identityColumn, resolve.targetColumn, lookupValues)
        }

    return elements.map { element ->
        buildMap {
            resolves.forEachIndexed { index, resolve ->
                if (resolve.skip(element)) return@forEachIndexed
                val lookupValue = resolve.valueSupplier(element)
                put(
                    resolve.fkColumn,
                    lookupValue?.let {
                        lookups[index][it]
                            ?: throw missingReference(resolve.identityColumn, it)
                    },
                )
            }
        }
    }
}

/**
 * The target keys for the public target ids [ids] of [junction] - every id itself when the junction
 * has no [JunctionWrite.targetResolve].
 *
 * @throws ReferencedEntityNotFoundException for the first id without a target row.
 */
internal suspend fun RowWriter.resolveJunctionTargets(
    junction: JunctionWrite<*>,
    ids: Set<Any?>,
): Map<Any?, Any?> {
    val resolve = junction.targetResolve ?: return ids.associateWith { it }

    val lookup = lookup(resolve.identityColumn, resolve.rawColumn, ids.filterNotNull().toSet())
    return ids.associateWith { id ->
        id?.let {
            lookup[it]
                ?: throw missingReference(resolve.identityColumn, it)
        }
    }
}

/** [target]'s value per value of [identity] for the rows matching [values], in one query. */
private suspend fun RowWriter.lookup(
    identity: TableField<*, *>,
    target: TableField<*, *>,
    values: Set<Any>,
): Map<Any?, Any?> {
    if (values.isEmpty()) return emptyMap()
    val query =
        dsl
            .select(identity.`as`("stx_identity"), target.`as`("stx_target"))
            .from(identity.owningTable())
            .where(identity.isOneOf(values))
    return executor.executeAndGetAll(query).associate {
        it.rawOrNull("stx_identity") to
            it.rawOrNull("stx_target")
    }
}

private fun missingReference(
    identity: TableField<*, *>,
    value: Any?,
) = ReferencedEntityNotFoundException(identity.owningTable().name, identity.name, value)

/**
 * Inserts the owned one-to-one rows of [commands] for every one of [writes] - one batch per write -
 * and returns per command the parent foreign-key values pointing at them.
 */
internal suspend fun <C> RowWriter.createOwnedChildren(
    writes: List<OwnedChildCreateWrite<C, *>>,
    commands: List<C>,
): List<RowValues> {
    if (writes.isEmpty()) return commands.map { emptyMap() }

    val perWrite = writes.map { write -> createOwnedChildren(write, commands) }

    return commands.indices.map { index ->
        mergeDisjoint(*perWrite.map { it[index] }.toTypedArray())
    }
}

private suspend fun <C, C2> RowWriter.createOwnedChildren(
    write: OwnedChildCreateWrite<C, C2>,
    commands: List<C>,
): List<RowValues> {
    val children = commands.map(write.childCommand)
    val present = children.withIndex().mapNotNull { (index, child) -> child?.let { index to it } }

    val childCommands = present.map { it.second }

    val foreignKeys = resolveForeignKeys(write.childFkResolves, childCommands)
    val rows =
        childCommands.mapIndexed {
            index,
            child,
            ->
            mergeDisjoint(write.childMapper.map(child).values, foreignKeys[index])
        }

    val inserted = insertReturning(write.childTable, write.childIdColumn, rows)
    val keyByCommand =
        present
            .map { it.first }
            .zip(
                inserted.map { it.rawOrNull(KEY_ALIAS) },
            ).toMap()
    // A command without a child still writes the column, as NULL: every row of one batch insert
    // writes the same columns.
    return commands.indices.map { index -> mapOf(write.parentFkColumn to keyByCommand[index]) }
}

/** `NOT soft-deleted` for [softDeleteColumn], or `null` without one. */
internal fun activeRows(softDeleteColumn: TableField<*, *>?): Condition? =
    softDeleteColumn?.untyped()?.isNull

/** [conditions] combined with `AND`, ignoring `null`s. */
internal fun allOf(vararg conditions: Condition?): Condition = DSL.and(conditions.filterNotNull())
